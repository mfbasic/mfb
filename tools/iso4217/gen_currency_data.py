#!/usr/bin/env python3
"""Generate packages/currency/src/data.mfb from the vendored ISO 4217 list.

    python3 tools/iso4217/gen_currency_data.py > packages/currency/src/data.mfb

The artifact goes to stdout and a statistics line goes to stderr.
`scripts/check-generated.sh` re-runs this script and fails on any difference.

Pipeline:
  1. check third_party/iso4217/<published>/list-one.xml against its SHA256SUMS;
  2. read every <CcyNtry> that names a code (Antarctica's entry names none);
  3. fail closed on any input that packages/currency does not handle;
  4. emit data.mfb: the publication date, the sorted code list, and the minor
     units of each code.

The checks in step 3 are the premises packages/currency relies on: a code is
three ASCII capitals, a code's minor units agree across every country that uses
it, and no currency has more decimal places than Money's five.
"""

import hashlib
import os
import re
import sys
import xml.etree.ElementTree as ET

PUBLISHED = "2026-09-17"

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VENDOR = os.path.join(ROOT, "third_party", "iso4217", PUBLISHED)
LIST = "list-one.xml"

CODE = re.compile(r"^[A-Z]{3}$")
# Money keeps five decimal places, so a currency with more minor units than
# that could not be rounded to them.
MAX_MINOR_UNITS = 5
# ISO 4217 writes "N.A." for a code with no minor unit (gold, the SDR, XXX).
NO_MINOR_UNIT = "N.A."
# The value data.mfb returns for such a code; currency::minorUnits maps it to 5.
NO_MINOR_UNIT_VALUE = -2


def fail(message):
    sys.stderr.write("gen_currency_data: %s\n" % message)
    sys.exit(1)


def verify_checksum():
    expected = {}
    with open(os.path.join(VENDOR, "SHA256SUMS"), encoding="ascii") as f:
        for line in f:
            digest, name = line.split()
            expected[name] = digest
    with open(os.path.join(VENDOR, LIST), "rb") as f:
        actual = hashlib.sha256(f.read()).hexdigest()
    if expected.get(LIST) != actual:
        fail("checksum mismatch for %s: SHA256SUMS has %s, file hashes to %s"
             % (LIST, expected.get(LIST), actual))


def read_codes():
    root = ET.parse(os.path.join(VENDOR, LIST)).getroot()
    if root.get("Pblshd") != PUBLISHED:
        fail("%s says it was published %s, but PUBLISHED is %s"
             % (LIST, root.get("Pblshd"), PUBLISHED))
    minor = {}
    for entry in root.iter("CcyNtry"):
        code = entry.findtext("Ccy")
        if code is None:
            continue
        code = code.strip()
        units = (entry.findtext("CcyMnrUnts") or "").strip()
        if not CODE.match(code):
            fail("code %r is not three ASCII capitals" % code)
        if units == NO_MINOR_UNIT:
            value = NO_MINOR_UNIT_VALUE
        elif units.isdigit() and int(units) <= MAX_MINOR_UNITS:
            value = int(units)
        else:
            fail("code %s has minor units %r, not 0..%d or %s"
                 % (code, units, MAX_MINOR_UNITS, NO_MINOR_UNIT))
        if code in minor and minor[code] != value:
            fail("code %s has minor units %r in one entry and %r in another"
                 % (code, minor[code], value))
        minor[code] = value
    if not minor:
        fail("%s names no currency codes" % LIST)
    return minor


def emit(minor):
    codes = sorted(minor)
    out = []
    w = out.append
    w("' GENERATED by tools/iso4217/gen_currency_data.py from third_party/iso4217")
    w("' (ISO 4217 List One, published %s)." % PUBLISHED)
    w("' Do not edit: `sh scripts/check-generated.sh` fails on any hand change.")
    w("")
    w("' The publication date of the ISO 4217 list this package carries.")
    w("FUNC isoPublished() AS String")
    w("  RETURN \"%s\"" % PUBLISHED)
    w("END FUNC")
    w("")
    w("' Every ISO 4217 code in the list, ascending.")
    w("FUNC isoCodeList() AS List OF String")
    w("  RETURN [%s]" % ", ".join("\"%s\"" % c for c in codes))
    w("END FUNC")
    w("")
    w("' The minor units of an upper-case ISO 4217 code: its decimal places,")
    w("' %d for a listed code with no minor unit (%s), or -1 for a code"
      % (NO_MINOR_UNIT_VALUE, NO_MINOR_UNIT))
    w("' that is not in the list.")
    w("FUNC isoMinorUnits(code AS String) AS Integer")
    w("  MATCH code")
    for value in sorted(set(minor.values()), key=lambda v: (v < 0, v)):
        group = [c for c in codes if minor[c] == value]
        w("    CASE %s : RETURN %d" % (", ".join("\"%s\"" % c for c in group), value))
    w("    CASE ELSE : RETURN -1")
    w("  END MATCH")
    w("END FUNC")
    sys.stdout.write("\n".join(out) + "\n")
    counts = {}
    for value in minor.values():
        counts[value] = counts.get(value, 0) + 1
    summary = " ".join(
        "%s:%d" % (NO_MINOR_UNIT if v == NO_MINOR_UNIT_VALUE else v, counts[v])
        for v in sorted(counts, key=lambda v: (v < 0, v)))
    sys.stderr.write("codes %d minor-units %s\n" % (len(codes), summary))


def main():
    verify_checksum()
    emit(read_codes())


if __name__ == "__main__":
    main()
