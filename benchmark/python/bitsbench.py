"""Bits-group benchmark (bits:: package surface) — one row per op.

GENERATED by benchmark/gen_bits.py — do not edit by hand; regenerate:
  python3 gen_bits.py py > python/bitsbench.py

Each row folds acc = bxor(acc, OP(x[, k])) over x = 0..N-1. Python ints are
unbounded, so every op is masked back to 64 bits and the printed checksum is
reinterpreted as signed two's-complement to line up with mfb / C.
"""
import sys

RUN = 1
now_ns = None
record = None

MASK64 = (1 << 64) - 1
MASK32 = (1 << 32) - 1
MASK16 = (1 << 16) - 1


def _band(a, b):
    return (a & b) & MASK64


def _bor(a, b):
    return (a | b) & MASK64


def _bxor(a, b):
    return (a ^ b) & MASK64


def _bnot(x):
    return (~x) & MASK64


def _sl(x, n):
    return (x << n) & MASK64


def _sr(x, n):
    return (x & MASK64) >> n


def _sra(x, n):
    v = x & MASK64
    if v >> 63:
        v -= (1 << 64)
    return (v >> n) & MASK64


def _rl32(x, n):
    v = x & MASK32
    n &= 31
    return ((v << n) | (v >> (32 - n))) & MASK32 if n else v


def _rr32(x, n):
    v = x & MASK32
    n &= 31
    return ((v >> n) | (v << (32 - n))) & MASK32 if n else v


def _rl64(x, n):
    v = x & MASK64
    n &= 63
    return ((v << n) | (v >> (64 - n))) & MASK64 if n else v


def _rr64(x, n):
    v = x & MASK64
    n &= 63
    return ((v >> n) | (v << (64 - n))) & MASK64 if n else v


def _clz(x):
    v = x & MASK64
    return 64 if v == 0 else 64 - v.bit_length()


def _ctz(x):
    v = x & MASK64
    return 64 if v == 0 else (v & -v).bit_length() - 1


def _popcount(x):
    return bin(x & MASK64).count("1")


def _bswap16(x):
    v = x & MASK16
    return ((v & 0xFF) << 8) | ((v >> 8) & 0xFF)


def _bswap32(x):
    v = x & MASK32
    return (((v & 0x000000FF) << 24) | ((v & 0x0000FF00) << 8)
            | ((v & 0x00FF0000) >> 8) | ((v & 0xFF000000) >> 24)) & MASK32


def _bswap64(x):
    v = x & MASK64
    r = 0
    for _ in range(8):
        r = (r << 8) | (v & 0xFF)
        v >>= 8
    return r & MASK64


def _to_signed64(x):
    v = x & MASK64
    return v - (1 << 64) if v >> 63 else v


