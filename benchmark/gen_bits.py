#!/usr/bin/env python3
"""Generator for the split `bits` benchmark across all three languages.

One row per bits:: op (was a single bundled `bits ops` row). Each row folds
`acc = bxor(acc, OP(i[, k]))` over i = 0..N-1, so the checksum is a deterministic
64-bit pattern identical in mfb / C / Python (reported signed). Bits are
Integer-only, so there is no Fixed/Dynamic split.

Regenerate (run from benchmark/):
  python3 gen_bits.py mfb > mfb/src/bits.mfb
  python3 gen_bits.py c   > c/bitsbench.c
  python3 gen_bits.py py  > python/bitsbench.py
"""
import sys

N = 200000
C = '6148914691236517205'  # 0x5555555555555555, positive in signed i64

# The accumulator is rotated before each XOR-fold so results over the contiguous
# i-range don't linearly cancel to 0 (AND/shift/rotate all distribute over XOR).
# The rotate is a fixed mixer present in every row, so it is uniform overhead;
# the op under test is the differentiator. Seed is the 32-bit FNV offset basis.
SEED = '2166136261'

# name, mfb expr (driver i), C expr (driver x=u64 i), Python expr (driver x=i)
OPS = [
    ('band',     f'bits::band(i, {C})',      f'(x & {C}ULL)',                        f'_band(x, {C})'),
    ('bor',      f'bits::bor(i, {C})',       f'(x | {C}ULL)',                        f'_bor(x, {C})'),
    ('bxor',     f'bits::bxor(i, {C})',      f'(x ^ {C}ULL)',                        f'_bxor(x, {C})'),
    ('bnot',     'bits::bnot(i)',            '(~x)',                                 '_bnot(x)'),
    ('sl',       'bits::sl(i, 3)',           '(x << 3)',                             '_sl(x, 3)'),
    ('sr',       'bits::sr(i, 3)',           '(x >> 3)',                             '_sr(x, 3)'),
    ('sra',      'bits::sra(i, 2)',          '(uint64_t)((int64_t)x >> 2)',          '_sra(x, 2)'),
    ('rl32',     'bits::rl32(i, 5)',         '(uint64_t)rotl32((uint32_t)x, 5)',     '_rl32(x, 5)'),
    ('rr32',     'bits::rr32(i, 9)',         '(uint64_t)rotr32((uint32_t)x, 9)',     '_rr32(x, 9)'),
    ('rl64',     'bits::rl64(i, 7)',         'rotl64(x, 7)',                         '_rl64(x, 7)'),
    ('rr64',     'bits::rr64(i, 3)',         'rotr64(x, 3)',                         '_rr64(x, 3)'),
    ('clz',      'bits::clz(i)',             '(uint64_t)clz64(x)',                   '_clz(x)'),
    ('ctz',      'bits::ctz(i)',             '(uint64_t)ctz64(x)',                   '_ctz(x)'),
    ('popCount', 'bits::popCount(i)',        '(uint64_t)__builtin_popcountll(x)',    '_popcount(x)'),
    ('bswap16',  'bits::bswap16(i)',         '(uint64_t)__builtin_bswap16((uint16_t)x)', '_bswap16(x)'),
    ('bswap32',  'bits::bswap32(i)',         '(uint64_t)__builtin_bswap32((uint32_t)x)', '_bswap32(x)'),
    ('bswap64',  'bits::bswap64(i)',         '__builtin_bswap64(x)',                 '_bswap64(x)'),
]


def emit_mfb():
    print("""\
' Bits-group benchmark (bits:: package). GENERATED by benchmark/gen_bits.py — do
' not edit by hand; edit the generator and regenerate:
'   python3 gen_bits.py mfb > mfb/src/bits.mfb
'
' One row per bits:: op. Each folds acc = bxor(acc, OP(i[, k])) over i=0..N-1 so
' the checksum is a deterministic 64-bit pattern identical across mfb / C /
' Python. Bits are Integer-only, so there is no Fixed/Dynamic split.
IMPORT io
IMPORT bits
IMPORT collections
IMPORT datetime""")
    for name, mfb, _c, _py in OPS:
        print(f"""
FUNC test_bits_{name}(run AS Integer, tests AS List OF BenchResult) AS List OF BenchResult
  MUT times AS List OF Integer = []
  MUT checksum AS Integer = 0
  FOR r = 0 TO run - 1
    LET t0 AS Integer = datetime::monotonicNanos()
    MUT acc AS Integer = {SEED}
    FOR i = 0 TO {N - 1}
      acc = bits::bxor(bits::rl64(acc, 7), {mfb})
    NEXT
    checksum = acc
    LET t1 AS Integer = datetime::monotonicNanos()
    times = collections::append(times, t1 - t0)
  NEXT
  io::printError("bits_{name} = " & toString(checksum))
  RETURN collections::append(tests, makeResult("bits", "{name}", times))
END FUNC""")


def emit_c():
    print("""\
/* GROUP: bits (bits:: package coverage) — one row per op.
 * GENERATED by benchmark/gen_bits.py — do not edit by hand; regenerate:
 *   python3 gen_bits.py c > c/bitsbench.c
 *
 * Each row folds acc ^= OP(x[, k]) over x = 0..N-1 on uint64_t, reported as a
 * signed i64 so the checksum matches mfb / Python. clz(0)/ctz(0) = 64 (mfb's
 * defined result); the 32-bit ops act on the low 32 bits and zero-extend. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#include "bench.h"
#include "bitsbench.h"

static inline uint64_t rotl64(uint64_t v, unsigned s) {
  s &= 63u;
  return s ? (v << s) | (v >> (64 - s)) : v;
}
static inline uint64_t rotr64(uint64_t v, unsigned s) {
  s &= 63u;
  return s ? (v >> s) | (v << (64 - s)) : v;
}
static inline uint32_t rotl32(uint32_t v, unsigned s) {
  s &= 31u;
  return s ? (v << s) | (v >> (32 - s)) : v;
}
static inline uint32_t rotr32(uint32_t v, unsigned s) {
  s &= 31u;
  return s ? (v >> s) | (v << (32 - s)) : v;
}
static inline int clz64(uint64_t v) { return v ? __builtin_clzll(v) : 64; }
static inline int ctz64(uint64_t v) { return v ? __builtin_ctzll(v) : 64; }""")
    for name, _mfb, c, _py in OPS:
        print(f"""
static void test_bits_{name}(void) {{
  long long *t = alloc_times();
  long long checksum = 0;
  for (int r = 0; r < RUN; r++) {{
    long long t0 = now_ns();
    uint64_t acc = {SEED}ULL;
    for (int i = 0; i < {N}; i++) {{
      uint64_t x = (uint64_t)i;
      acc = rotl64(acc, 7) ^ ({c});
    }}
    checksum = (long long)acc;
    t[r] = now_ns() - t0;
  }}
  fprintf(stderr, "bits_{name} = %lld\\n", checksum);
  record("bits", "{name}", t, RUN);
  free(t);
}}""")
    print("\nvoid run_bits_group(void) {")
    for name, _mfb, _c, _py in OPS:
        print(f"  test_bits_{name}();")
    print("}")


def emit_py():
    print('''\
"""Bits-group benchmark (bits:: package surface) — one row per op.

GENERATED by benchmark/gen_bits.py — do not edit by hand; regenerate:
  python3 gen_bits.py py > python/bitsbench.py

Each row folds acc = bxor(acc, OP(x[, k])) over x = 0..N-1. Python ints are
unbounded, so every op is masked back to 64 bits and the printed checksum is
reinterpreted as signed two's-complement to line up with mfb / C.
"""
import sys

RUN = 1
now_ns = None
record = None

MASK64 = (1 << 64) - 1
MASK32 = (1 << 32) - 1
MASK16 = (1 << 16) - 1


def _band(a, b):
    return (a & b) & MASK64


def _bor(a, b):
    return (a | b) & MASK64


def _bxor(a, b):
    return (a ^ b) & MASK64


def _bnot(x):
    return (~x) & MASK64


def _sl(x, n):
    return (x << n) & MASK64


def _sr(x, n):
    return (x & MASK64) >> n


def _sra(x, n):
    v = x & MASK64
    if v >> 63:
        v -= (1 << 64)
    return (v >> n) & MASK64


def _rl32(x, n):
    v = x & MASK32
    n &= 31
    return ((v << n) | (v >> (32 - n))) & MASK32 if n else v


def _rr32(x, n):
    v = x & MASK32
    n &= 31
    return ((v >> n) | (v << (32 - n))) & MASK32 if n else v


def _rl64(x, n):
    v = x & MASK64
    n &= 63
    return ((v << n) | (v >> (64 - n))) & MASK64 if n else v


def _rr64(x, n):
    v = x & MASK64
    n &= 63
    return ((v >> n) | (v << (64 - n))) & MASK64 if n else v


def _clz(x):
    v = x & MASK64
    return 64 if v == 0 else 64 - v.bit_length()


def _ctz(x):
    v = x & MASK64
    return 64 if v == 0 else (v & -v).bit_length() - 1


def _popcount(x):
    return bin(x & MASK64).count("1")


def _bswap16(x):
    v = x & MASK16
    return ((v & 0xFF) << 8) | ((v >> 8) & 0xFF)


def _bswap32(x):
    v = x & MASK32
    return (((v & 0x000000FF) << 24) | ((v & 0x0000FF00) << 8)
            | ((v & 0x00FF0000) >> 8) | ((v & 0xFF000000) >> 24)) & MASK32


def _bswap64(x):
    v = x & MASK64
    r = 0
    for _ in range(8):
        r = (r << 8) | (v & 0xFF)
        v >>= 8
    return r & MASK64


def _to_signed64(x):
    v = x & MASK64
    return v - (1 << 64) if v >> 63 else v''')
    for name, _mfb, _c, py in OPS:
        print(f'''

def test_bits_{name}():
    times = []
    checksum = 0
    for _ in range(RUN):
        t0 = now_ns()
        acc = {SEED}
        for i in range({N}):
            x = i
            acc = _bxor(_rl64(acc, 7), {py})
        checksum = _to_signed64(acc)
        times.append(now_ns() - t0)
    print("bits_{name} = %d" % checksum, file=sys.stderr)
    record("bits", "{name}", times)''')
    print('''

def run_all(run, now_ns_fn, record_fn):
    global RUN, now_ns, record
    RUN, now_ns, record = run, now_ns_fn, record_fn''')
    for name, _mfb, _c, _py in OPS:
        print(f'    test_bits_{name}()')


def main():
    lang = sys.argv[1] if len(sys.argv) > 1 else 'mfb'
    {'mfb': emit_mfb, 'c': emit_c, 'py': emit_py}[lang]()


if __name__ == '__main__':
    main()
