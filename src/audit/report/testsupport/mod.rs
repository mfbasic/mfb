pub(in crate::audit) fn finding(code: &str, category: &str, severity: Severity) -> Finding {
    Finding {
        code: code.to_string(),
        category: category.to_string(),
        severity,
        message: format!("message for {code}"),
        path: None,
        line: None,
        package: None,
    }
}

